#!/usr/bin/env bash
# Verify or capture the pinned C++ reference baseline for the Rust rewrite.
#
# Usage:
#   bash tools/reference-baseline.sh check
#   bash tools/reference-baseline.sh capture
#   bash tools/reference-baseline.sh --help
#
# Environment:
#   SPIRULA_REFERENCE_REPO   reference checkout (default: ../spirula-studio)
#   SPIRULA_BASELINE_LOG_DIR capture root (default: artifacts/reference-baseline)
#
# `check` exits 0 only when the checkout is at the pinned commit with no
# tracked modifications. It never builds the reference project; see
# docs/phase-0/reference-baseline.md for the build and test commands.

set -euo pipefail

PINNED_REPO_URL="https://github.com/harry7557558/spirula-studio.git"
PINNED_COMMIT="9a24f09927944a795e7ba1bd8243a625bf419479"
PINNED_VERSION="2026.10.16"

REPO_ROOT="$(git rev-parse --show-toplevel)"
REFERENCE_REPO="${SPIRULA_REFERENCE_REPO:-${REPO_ROOT}/../spirula-studio}"
LOG_ROOT="${SPIRULA_BASELINE_LOG_DIR:-${REPO_ROOT}/artifacts/reference-baseline}"

usage() {
    sed -n '2,16p' "$0" | sed 's/^# \{0,1\}//'
}

version_of() {
    local exe="$1"
    if command -v "$exe" >/dev/null 2>&1; then
        "$exe" --version 2>&1 | head -n 1
    else
        printf 'not installed\n'
    fi
}

print_environment() {
    printf 'os: %s\n' "$(uname -srm)"
    if command -v sw_vers >/dev/null 2>&1; then
        printf 'macos: %s\n' "$(sw_vers -productVersion)"
    fi
    printf 'cmake: %s\n' "$(version_of cmake)"
    printf 'ninja: %s\n' "$(version_of ninja)"
    printf 'python3: %s\n' "$(version_of python3)"
    printf 'clang++: %s\n' "$(version_of clang++)"
    printf 'g++: %s\n' "$(version_of g++)"
    printf 'nvcc: %s\n' "$(version_of nvcc)"
    printf 'slangc: %s\n' "$(version_of slangc)"
    printf 'vulkaninfo: %s\n' "$(version_of vulkaninfo)"
    printf 'rustc: %s\n' "$(version_of rustc)"
    printf 'cargo: %s\n' "$(version_of cargo)"
}

check_reference() {
    if [ ! -d "$REFERENCE_REPO/.git" ]; then
        printf 'error: no reference checkout at %s\n' "$REFERENCE_REPO" >&2
        printf 'set SPIRULA_REFERENCE_REPO to the spirula-studio checkout\n' >&2
        return 2
    fi

    local head url dirty
    head="$(git -C "$REFERENCE_REPO" rev-parse HEAD)"
    url="$(git -C "$REFERENCE_REPO" config --get remote.origin.url || true)"
    dirty="$(git -C "$REFERENCE_REPO" status --porcelain --untracked-files=no)"

    printf 'reference: %s\n' "$REFERENCE_REPO"
    printf 'remote:    %s\n' "${url:-<none>}"
    printf 'HEAD:      %s\n' "$head"

    local failed=0
    if [ "$head" != "$PINNED_COMMIT" ]; then
        printf 'error: HEAD is not the pinned commit %s\n' "$PINNED_COMMIT" >&2
        failed=1
    fi
    if [ -n "$url" ] && [ "$url" != "$PINNED_REPO_URL" ]; then
        printf 'error: remote is not %s\n' "$PINNED_REPO_URL" >&2
        failed=1
    fi
    if [ -n "$dirty" ]; then
        printf 'error: tracked modifications make this checkout invalid as evidence:\n%s\n' "$dirty" >&2
        failed=1
    fi

    printf '\ntoolchain:\n'
    print_environment

    if [ "$failed" -ne 0 ]; then
        return 1
    fi
    printf '\nbaseline OK (application version %s)\n' "$PINNED_VERSION"
}

capture_reference() {
    local stamp out
    stamp="$(date -u +%Y%m%dT%H%M%SZ)"
    out="${LOG_ROOT}/${stamp}"
    mkdir -p "$out"

    print_environment > "${out}/environment.txt"
    {
        printf 'expected remote: %s\n' "$PINNED_REPO_URL"
        printf 'expected commit: %s\n' "$PINNED_COMMIT"
        printf 'expected version: %s\n' "$PINNED_VERSION"
        printf 'checkout: %s\n\n' "$REFERENCE_REPO"
        if [ -d "$REFERENCE_REPO/.git" ]; then
            git -C "$REFERENCE_REPO" show -s \
                --format='commit %H%nparents %P%nauthor %an <%ae>%ndate %cI%nsubject %s' HEAD
            printf '\nstatus (tracked):\n'
            git -C "$REFERENCE_REPO" status --porcelain --untracked-files=no
        else
            printf 'checkout missing\n'
        fi
    } > "${out}/git.txt"

    cat > "${out}/README.md" <<'EOF'
# Reference baseline capture

Generated by `bash tools/reference-baseline.sh capture`.

- `environment.txt` — local toolchain versions.
- `git.txt` — expected and actual reference identity.

Build/test commands and the evidence policy are in
`docs/phase-0/reference-baseline.md`. Record actual runs in this directory,
for example:

```bash
bash build_develop.bash -DSS_BACKEND=vulkan 2>&1 | tee build.log
./build/spirula train --help               2>&1 | tee smoke.log
```

This directory is gitignored; commit only distilled findings to
`docs/phase-0/`.
EOF

    printf 'captured to %s\n' "$out"
    set +e
    check_reference > "${out}/baseline-check.txt" 2>&1
    local status=$?
    set -e
    cat "${out}/baseline-check.txt"
    if [ "$status" -ne 0 ]; then
        printf 'warning: capture recorded, but the checkout is not at the pinned baseline\n' >&2
    fi
    return 0
}

main() {
    case "${1:-check}" in
        check) check_reference ;;
        capture) capture_reference ;;
        -h|--help|help) usage ;;
        *)
            printf 'error: unknown command %s\n\n' "$1" >&2
            usage >&2
            return 2
            ;;
    esac
}

main "$@"
